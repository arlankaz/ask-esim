export interface EsimPlan extends SelectedTariff {
  priceUsd: number;
  providerPlanId: string;
}

export function getEsimPlans(countryId: string): EsimPlan[] {
  const code = countryId === 'ME_' ? 'ME' : countryId;
  const source = PRODUCTS[code];

  if (!source) return [];

  return source.split('|').map((entry) => {
    const [volume, providerPlanId, amount] = entry.split(':');
    const priceUsd = Number(amount);

    return {
      id: providerPlanId,
      providerPlanId,
      volume: `${volume} GB`,
      days: 30,
      mult: 1,
      priceUsd,
      priceKzt: Math.round(priceUsd * 500),
    };
  });
}

export function getLowestPriceKzt(
  countryId: string
): number | null {
  const plans = getEsimPlans(countryId);

  if (!plans.length) return null;

  return Math.min(...plans.map((plan) => plan.priceKzt));
}

export function hasEsimPlans(countryId: string): boolean {
  return getEsimPlans(countryId).length > 0;
}
